// Storage, authorization and session counters only; never renders or validates visual effects.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const ts = require('C:/ProgramData/cocos/editors/Creator/3.8.6/resources/resources/3d/engine/node_modules/typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2018 },
}).outputText, filename);
const root = path.resolve(__dirname, '../assets/scripts');
const { SmokeLabStore, SMOKE_LAB_STORAGE_KEY } = require(path.join(root, 'persistence/SmokeLabStore.ts'));
const { DEFAULT_SMOKE_SCHEME, SMOKE_COLORS, LAB_TABS, RING_FORMATIONS } = require(path.join(root, 'lab/SmokeLabModel.ts'));
const { SessionModel } = require(path.join(root, 'domain/SessionModel.ts'));
const { SmokeLabPreview } = require(path.join(root, 'lab/SmokeLabPreview.ts'));
const day = '2026-10-16', now = new Date(2026, 9, 16, 12).getTime(), tomorrow = now + 86400000;
let days = 1, context = { boxId: 'wang-xi:1', typeId: 'wang-xi', packName: '王溪', sequence: 1 };
const data = new Map();
const storage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value) };
const store = new SmokeLabStore(storage, () => context, () => days);
const defaults = { ...DEFAULT_SMOKE_SCHEME };
const blue = { ...defaults, exhaleColor: 'ice-blue' };
const red = { ...defaults, exhaleColor: 'lava-red' };
assert.deepEqual(store.snapshot(now).scheme, defaults);
assert.equal(store.grantAccess('lab:exhale-color', day, now), false, 'entry remains locked below day 2');
days = 2;
assert.equal(store.save('box', blue, context.boxId, now), false, 'UI state cannot bypass daily editing access');
assert.equal(store.grantAccess('lab:exhale-color', day, now), true);
assert.equal(store.save('global', blue, context.boxId, now), true);
assert.equal(store.snapshot(now).source, 'global');
assert.equal(store.save('type', red, context.boxId, now), true);
assert.equal(store.snapshot(now).source, 'type');
assert.equal(store.save('box', blue, context.boxId, now), true);
assert.equal(store.snapshot(now).source, 'box');
assert.equal(store.restore('box', context.boxId), true);
assert.deepEqual(store.snapshot(now).scheme, defaults, 'explicit box default blocks inherited custom type/global');
assert.equal(store.save('type', red, context.boxId, now), true);
assert.equal(store.snapshot(now).source, 'type', 'type save clears its per-box overrides');
context = { ...context, boxId: 'wang-xi:2', sequence: 2 };
assert.deepEqual(store.snapshot(now).scheme, red, 'future boxes inherit the saved type');
assert.equal(store.save('box', blue, 'wang-xi:1', now), false, 'stale box context cannot save to a different box');
assert.equal(store.save('box', blue, context.boxId, now), true);
assert.equal(store.save('global', red, context.boxId, now), true);
assert.equal(store.snapshot(now).source, 'global', 'global save removes all lower overrides');
assert.equal(store.granted('lab:exhale-color', tomorrow), false);
assert.deepEqual(store.runtime(tomorrow).scheme, red, 'expired editing access does not erase saved schemes');
assert.equal(store.save('box', blue, context.boxId, tomorrow), false);
assert.equal(store.grantAccess('lab:exhale-color', day, tomorrow), false, 'cross-midnight preview result cannot grant tomorrow');
assert.equal(store.eligible('ring:droplet'), false, 'unimplemented task completion is never fabricated');
assert.equal(store.grantAccess('ring:droplet', day, now), false);
assert.equal(store.eligible('ring:text'), false, 'national collection reward remains locked');
assert.equal(store.save('box', { ...red, ringShape: 'heart' }, context.boxId, now), false);
assert.equal(store.grantAccess('ring:heart', day, now), true);
assert.equal(store.grantAccess('ring:square', day, now), true);
assert.equal(store.grantAccess('ring:petal', day, now), true);
assert.equal(store.groupState('ring', now).complete, true);
assert.equal(store.groupState('ring', tomorrow).granted, false);
assert.equal(store.grantAccess('group:ring', '2026-10-17', tomorrow), true, 'completed discovery group can be renewed on a later day');
assert.equal(store.save('box', { ...red, ringShape: 'heart' }, context.boxId, tomorrow), true);
assert.equal(store.grantAccess('formation:tunnel', day, now), false, 'formation requires unlimited-ring access');
assert.equal(store.grantAccess('ring:unlimited', day, now), true);
assert.equal(store.grantAccess('formation:tunnel', day, now), true);
assert.equal(store.setInteraction({ formation: 'tunnel', formationEnabled: true }, now), true);
assert.equal(store.runtime(now).formation, 'tunnel');
assert.equal(store.runtime(tomorrow).formation, null, 'daily formation and unlimited privileges expire');
assert.equal(store.setInteraction({ handSmoke: true }, now), false);
days = 3; assert.equal(store.runtime(now).directionalRing, true);
assert.equal(store.setInteraction({ handSmoke: true }, now), false);
days = 4; assert.equal(store.setInteraction({ handSmoke: true }, now), true);
assert.equal(store.runtime(now).handSmoke, true);
assert.equal(store.restore('global', context.boxId), true);
assert.deepEqual(store.snapshot(now).scheme, defaults);
assert.equal(store.runtime(now).handSmoke, true, 'resetting appearance preserves interaction preferences');
assert.equal(store.setInteraction({ formation: 'bad' }, now), false);
assert.equal(store.setInteraction({ handSmoke: 'bad' }, now), false);
assert.equal(store.grantAccess('bad', day, now), false);
assert.equal(store.save('global', { ...defaults, exhaleStyle: 'bad' }, context.boxId, now), false);
assert.equal(store.save('global', { ...defaults, exhaleColor: 'zuguo-exhale' }, context.boxId, now), false);
assert.equal(LAB_TABS.length, 6); assert.equal(SMOKE_COLORS.length, 15); assert.equal(RING_FORMATIONS.length, 4);

// Leaving/returning to the lab changes permission on the same model, never resets a cigarette.
const model = new SessionModel(); model.beginLighting(); model.update(0.7); model.beginInhale(); model.update(2); model.releaseInhale();
for (let i = 0; i < 3; i++) assert.equal(model.emitSmokeRing().accepted, true);
const before = model.snapshot;
assert.equal(model.emitSmokeRing().accepted, false);
model.setUnlimitedRings(true);
assert.equal(model.emitSmokeRing().accepted, true);
assert.equal(model.snapshot.remaining, before.remaining);
assert.equal(model.snapshot.elapsedSeconds, before.elapsedSeconds);
model.setUnlimitedRings(false);
assert.equal(model.emitSmokeRing().accepted, false, 'expiry restores the per-cigarette cap without resetting count');
model.update(3); assert.equal(model.emitSmokeRing().accepted, false, 'unlimited does not bypass exhaling phase');

data.set(SMOKE_LAB_STORAGE_KEY, '{broken');
assert.equal(store.snapshot(now), null);
assert.equal(store.save('global', defaults, context.boxId, now), false, 'corrupt data is not overwritten');
assert.equal(new SmokeLabStore(null, () => context, () => days).snapshot(now), null);
const failing = new SmokeLabStore({ getItem: () => null, setItem: () => { throw Error('quota'); } }, () => context, () => days);
assert.equal(failing.grantAccess('lab:style', day, now), false, 'storage failure cannot report successful unlock');
const groups = new SmokeLabStore(storage, () => context, () => days);
data.delete(SMOKE_LAB_STORAGE_KEY);
assert.equal(groups.grantAccess('ring:unlimited', day, now), true);
for (const option of RING_FORMATIONS) assert.equal(groups.grantAccess(`formation:${option.id}`, day, now), true);
assert.equal(groups.groupState('formation', tomorrow).complete, true);
assert.equal(groups.grantAccess('group:formation', '2026-10-17', tomorrow), false, 'group renewal cannot bypass unlimited prerequisite');

// UI preview is independent of daily grants, the real save key and renderer runtime data.
const realSnapshot = groups.snapshot(now);
const realData = JSON.stringify([...data]);
const realRuntime = groups.runtime(now);
const preview = new SmokeLabPreview();
assert.equal(preview.save('box', blue, context), true);
assert.deepEqual(preview.resolve(realSnapshot).scheme, blue);
const readPreview = preview.resolve(realSnapshot);
readPreview.scheme.exhaleColor = 'mint';
assert.deepEqual(preview.resolve(realSnapshot).scheme, blue, 'returned UI data cannot mutate its saved preview');
assert.equal(preview.resolve(realSnapshot).source, 'box');
assert.equal(preview.save('type', red, context), true);
assert.equal(preview.resolve(realSnapshot).source, 'type', 'preview type save clears its local box override');
assert.equal(preview.restore('box', context), true);
assert.deepEqual(preview.resolve(realSnapshot).scheme, defaults);
assert.equal(preview.resolve(realSnapshot).source, 'default');
assert.equal(preview.save('global', blue, context), true);
assert.equal(preview.resolve(realSnapshot).source, 'global');
assert.equal(preview.resolve({ ...realSnapshot, context: { ...context, boxId: 'wang-xi:99' } }).scheme.exhaleColor, 'ice-blue');
preview.grant('ring:unlimited');
preview.setInteraction({ handSmoke: true, formationEnabled: true, formation: 'weave' });
assert.equal(preview.granted('ring:unlimited'), true);
assert.equal(preview.resolve(realSnapshot).interaction.formation, 'weave');
assert.equal(preview.restore('global', context), true);
assert.equal(preview.resolve(realSnapshot).interaction.formation, 'weave', 'reset only changes preview appearance');
assert.equal(preview.save('box', { ...defaults, exhaleColor: 'bad' }, context), false);
assert.equal(preview.resolve(null), null);
assert.equal(preview.save('box', blue, { ...context, boxId: null }), false);
assert.equal(JSON.stringify([...data]), realData, 'UI preview never writes real scheme or access storage');
assert.deepEqual(groups.runtime(now), realRuntime, 'UI preview never changes runtime smoke configuration');
assert.deepEqual(new SmokeLabPreview().resolve(realSnapshot).scheme, realSnapshot.scheme, 'preview resets when the app instance is rebuilt');
console.log('PASS: smoke lab scope precedence, defaults, rollover, stale context, task gates, interactions and session counters. Business checks only.');
